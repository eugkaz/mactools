import AppKit
import Observation
import UniformTypeIdentifiers

// MARK: - Clipboard history

struct ClipItem: Codable, Identifiable, Equatable {
    var id = UUID()
    var text: String?
    var imageFile: String?
    var files: [String]?
    var date = Date()
    var pinned = false
    var sourceApp: String?

    var preview: String {
        if let text { return text.trimmingCharacters(in: .whitespacesAndNewlines) }
        if let files { return files.map { ($0 as NSString).lastPathComponent }.joined(separator: ", ") }
        return "Изображение"
    }

    var kindIcon: String {
        if imageFile != nil { return "photo" }
        if files != nil { return "doc" }
        guard let t = text?.trimmingCharacters(in: .whitespacesAndNewlines) else { return "text.alignleft" }
        if t.hasPrefix("http://") || t.hasPrefix("https://") { return "link" }
        if t.range(of: "^#?[0-9a-fA-F]{6}$", options: .regularExpression) != nil { return "paintpalette" }
        if (t.hasPrefix("{") && t.hasSuffix("}")) || (t.hasPrefix("[") && t.hasSuffix("]")) { return "curlybraces" }
        if t.hasPrefix("$ ") || t.hasPrefix("sudo ") || t.hasPrefix("git ") || t.hasPrefix("npm ") || t.hasPrefix("brew ") { return "terminal" }
        return "text.alignleft"
    }
}

@Observable
final class ClipboardStore {
    var items: [ClipItem] = []
    var flash: UUID?
    @ObservationIgnored private var lastCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored let imgDir = Persist.dir.appendingPathComponent("clips")
    static let ignored: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                       "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    init() {
        try? FileManager.default.createDirectory(at: imgDir, withIntermediateDirectories: true)
        items = Persist.load([ClipItem].self, "clipboard") ?? []
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        if !types.isDisjoint(with: Self.ignored) { return }
        let src = NSWorkspace.shared.frontmostApplication?.localizedName
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            add(ClipItem(files: urls.map(\.path), sourceApp: src))
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(ClipItem(text: s, sourceApp: src))
        } else if let img = NSImage(pasteboard: pb), let tiff = img.tiffRepresentation,
                  let rep = NSBitmapImageRep(data: tiff), let png = rep.representation(using: .png, properties: [:]) {
            let name = UUID().uuidString + ".png"
            try? png.write(to: imgDir.appendingPathComponent(name))
            add(ClipItem(imageFile: name, sourceApp: src))
        }
    }

    func add(_ item: ClipItem) {
        if let t = item.text, let i = items.firstIndex(where: { $0.text == t }) {
            var existing = items.remove(at: i)
            existing.date = Date()
            items.insert(existing, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        var unpinned = 0
        items = items.filter { it in
            if it.pinned { return true }
            unpinned += 1
            if unpinned > 80 { cleanup(it); return false }
            return true
        }
        save()
    }

    func cleanup(_ it: ClipItem) {
        if let f = it.imageFile { try? FileManager.default.removeItem(at: imgDir.appendingPathComponent(f)) }
    }

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if let t = item.text { pb.setString(t, forType: .string) }
        else if let f = item.files { pb.writeObjects(f.map { URL(fileURLWithPath: $0) as NSURL }) }
        else if let f = item.imageFile, let img = NSImage(contentsOf: imgDir.appendingPathComponent(f)) { pb.writeObjects([img]) }
        lastCount = pb.changeCount
        flash = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.9) { if self.flash == item.id { self.flash = nil } }
    }

    func image(_ item: ClipItem) -> NSImage? {
        item.imageFile.flatMap { NSImage(contentsOf: imgDir.appendingPathComponent($0)) }
    }

    func togglePin(_ item: ClipItem) {
        if let i = items.firstIndex(of: item) { items[i].pinned.toggle(); save() }
    }

    func remove(_ item: ClipItem) {
        cleanup(item)
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items.filter { !$0.pinned }.forEach(cleanup)
        items.removeAll { !$0.pinned }
        save()
    }

    func save() { Persist.save(items, "clipboard") }
}

// MARK: - Shelf

@Observable
final class ShelfStore {
    var paths: [String] = Persist.load([String].self, "shelf") ?? []

    var urls: [URL] { paths.map { URL(fileURLWithPath: $0) }.filter { FileManager.default.fileExists(atPath: $0.path) } }

    func add(_ urls: [URL]) {
        for u in urls where !paths.contains(u.path) { paths.append(u.path) }
        save()
    }
    func remove(_ u: URL) { paths.removeAll { $0 == u.path }; save() }
    func clear() { paths.removeAll(); save() }
    func save() { Persist.save(paths, "shelf") }

    func airdrop() {
        NSSharingService(named: .sendViaAirDrop)?.perform(withItems: urls)
    }
}

// MARK: - Launcher

@Observable
final class LauncherStore {
    var pinned: [String]
    var usage: [String: Int] = Persist.load([String: Int].self, "usage") ?? [:]
    @ObservationIgnored private var observer: NSObjectProtocol?

    init() {
        if let saved = Persist.load([String].self, "launcher") {
            pinned = saved
        } else {
            let home = FileManager.default.homeDirectoryForCurrentUser.path
            let candidates = [
                "/System/Applications/Utilities/Terminal.app", "/Applications/iTerm.app", "/Applications/Warp.app",
                "/Applications/Visual Studio Code.app", "/Applications/Cursor.app", "/Applications/Xcode.app",
                "/Applications/Docker.app", "/Applications/Postman.app", "/Applications/Telegram.app",
                "\(home)/Developer", "\(home)/Downloads", "\(home)/Desktop", "\(home)/Documents",
            ]
            pinned = candidates.filter { FileManager.default.fileExists(atPath: $0) }
        }
        observer = NSWorkspace.shared.notificationCenter.addObserver(forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) { [weak self] n in
            guard let self, let app = n.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication,
                  let path = app.bundleURL?.path, app.activationPolicy == .regular,
                  app.bundleIdentifier != Bundle.main.bundleIdentifier, app.bundleIdentifier != "com.apple.finder" else { return }
            self.usage[path, default: 0] += 1
            Persist.save(self.usage, "usage")
        }
    }

    var frequent: [String] {
        usage.filter { !pinned.contains($0.key) && FileManager.default.fileExists(atPath: $0.key) }
            .sorted { $0.value > $1.value }.prefix(8).map(\.key)
    }

    func add(_ urls: [URL]) {
        for u in urls where !pinned.contains(u.path) { pinned.append(u.path) }
        save()
    }
    func remove(_ p: String) { pinned.removeAll { $0 == p }; save() }
    func move(_ p: String, by d: Int) {
        guard let i = pinned.firstIndex(of: p) else { return }
        let j = max(0, min(pinned.count - 1, i + d))
        pinned.swapAt(i, j); save()
    }
    func save() { Persist.save(pinned, "launcher") }

    func open(_ p: String) {
        NSWorkspace.shared.open(URL(fileURLWithPath: p))
    }

    static func isFolder(_ p: String) -> Bool {
        var d: ObjCBool = false
        return FileManager.default.fileExists(atPath: p, isDirectory: &d) && d.boolValue && !p.hasSuffix(".app")
    }

    static func openFolder(_ p: String, with bundleID: String) {
        guard let app = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) else { NSSound.beep(); return }
        NSWorkspace.shared.open([URL(fileURLWithPath: p)], withApplicationAt: app, configuration: NSWorkspace.OpenConfiguration())
    }
}
